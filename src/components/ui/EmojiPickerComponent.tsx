const EmojiPickerComponent = ({ onEmojiSelect }) => {
  const [searchTerm, setSearchTerm] = useState('');
  const [hoveredIndex, setHoveredIndex] = useState<number | null>(null);
  const filteredEmojis = emojiList.filter((item) =>
    item.description.toLowerCase().includes(searchTerm.toLowerCase())
  );

  return (
    <div style={styles.emojiPicker}>
      <input
        type="text"
        placeholder="Tìm kiếm icons..."
        value={searchTerm}
        onChange={(e) => setSearchTerm(e.target.value)}
        style={styles.emojiSearchInput}
      />
      <div style={styles.emojiList}>
        {filteredEmojis.map((item, index) => (
          <span
            key={index}
            onClick={(e) => {
              e.preventDefault();
              e.stopPropagation();
              onEmojiSelect(item.emoji);
            }}
            style={{
              ...styles.emojiSpan,
              ...(hoveredIndex === index ? styles.emojiSpanHover : {})
            }}
            onMouseEnter={() => setHoveredIndex(index)}
            onMouseLeave={() => setHoveredIndex(null)}
          >
            {item.emoji}
          </span>
        ))}
      </div>
    </div>
  );
};

export default EmojiPickerComponent;
